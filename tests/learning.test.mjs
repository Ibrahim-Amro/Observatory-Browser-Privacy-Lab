import assert from 'node:assert/strict';
import {CHECKUP_STEPS,QUESTIONS,findQuestions,createLearningState,stepStatus,buildSessionAnswers,plainReport} from '../dist/learning.js';
const state=createLearningState();
const event=(title,category,kind='observed')=>({title,category,kind,detail:'Formats only; contents were not read.',time:'2026-10-26T12:00:00Z'});
state.observe(event('Synthetic page copy event','clipboard'));
assert.equal(state.read().latest.copy,undefined);
state.observe({...event('Page copy event','clipboard'),signal:true});
assert.equal(state.read().latest.copy,undefined,'a reading snapshot is not an action');
state.observe(event('Page copy event','clipboard'));
assert.equal(stepStatus('copy',state.read()).kind,'observed');
state.observe(event('Page lost focus','tabs'));
assert.equal(stepStatus('tabs',state.read()).done,false,'focus alone does not establish hidden state');
state.observe(event('Page became hidden','tabs'));
assert.equal(stepStatus('tabs',state.read()).done,true);
state.markClick(false);assert.equal(stepStatus('click',state.read()).done,false);
state.markClick(true);assert.equal(stepStatus('click',state.read()).done,true);
state.observe(event('Possible screenshot shortcut','screenshot','possible'));
assert.equal(stepStatus('screenshots',state.read()).done,false,'a clue never completes screenshot confirmation');
state.review('screenshots');
assert.equal(stepStatus('screenshots',state.read()).label,'Limit reviewed');
assert.equal(stepStatus('screenshots',state.read()).kind,'context');
state.skip('recognition');assert.match(stepStatus('recognition',state.read()).label,/Skipped/);
state.review('copy');assert.ok(!state.read().reviewed.includes('copy'),'observed-action steps cannot be manually passed');
const session={startedAt:'2026-10-26T11:00:00Z',summary:{counts:{clicks:3,copy:1,cut:0,paste:0,screenshot:1},totalEvents:110,retained:20},connection:{address:'203.0.113.20',family:'IPv4',sourceLabel:'This website',checkedAt:'2026-10-26T12:00:00Z',stale:true,location:{status:'available',city:'Private test city',country:'Fixture country'}},fingerprint:{groupingHash:'private-hash'},activeDemos:[]};
const answers=buildSessionAnswers(session,state.read());
assert.match(answers.find(a=>a.id==='screenshots').result,/No screenshot was confirmed/);
assert.equal(answers.find(a=>a.id==='screenshots').kind,'possible');
assert.match(answers.find(a=>a.id==='connection').result,/stale/);
assert.equal(stepStatus('connection',state.read(),session).done,true,'earlier valid result is retained and explicitly stale');
const report=plainReport(session,state.read());
assert.ok(!report.includes(session.connection.address)&&!report.includes('Private test city')&&!report.includes('private-hash'));
assert.match(report,/Retained feed entries: 20/);
assert.match(report,/All-time session entries: 110/);
const personal=plainReport(session,state.read(),{includePersonal:true});
assert.ok(personal.includes(session.connection.address)&&personal.includes('Private test city'));
assert.ok(!personal.includes('private-hash'));
assert.equal(findQuestions({search:'clipboard',topic:'Clipboard'}).length,2);
assert.equal(findQuestions({search:'nonexistent nonsense'}).length,0);
assert.equal(new Set(QUESTIONS.map(q=>q.id)).size,QUESTIONS.length);
assert.equal(new Set(CHECKUP_STEPS.map(q=>q.id)).size,6);
const retained=state.read();retained.latest.copy.title='Changed';assert.equal(state.read().latest.copy.title,'Page copy event');
state.reset();assert.deepEqual(state.read(),{latest:{},reviewed:[],skipped:[],sampleClick:false});
assert.equal(buildSessionAnswers({},state.read()).find(a=>a.id==='copy').kind,'context');
console.log('Guided progress, trusted evidence, screenshot limits, stale results, redacted reports, question search and reset passed.');
